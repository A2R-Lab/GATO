#!/usr/bin/env bash
# Build the faithful batched-CPU baseline (pysqpcpu: multi-threaded OSQP/QDLDL solver, the paper's Fig-3 CPU
# competitor) WITHOUT the heavy ROS + source-pinocchio install the upstream Dockerfile uses.
#
# The optional baseline uses its own pinned Pinocchio 3.8 environment, not
# GATO's Pinocchio 4.x or a sibling project's venv. See baselines/README.md.
# Build osqp + osqp-eigen into a local prefix; no sudo or system installation.
#
# Usage:
#   baselines/build_cpu_baseline.sh [VENV_DIR]      # default: <repo>/.venv-cpu-baseline
# After it finishes, run anything that imports pysqpcpu with:
#   source baselines/sqpcpu_env.sh                  # sets LD_LIBRARY_PATH + PYTHONPATH
#
# System prerequisites (Ubuntu): build-essential cmake>=3.24 git libeigen3-dev liburdfdom-dev.
#   (pinocchio/hpp-fcl/Eigen C++ come from the venv's cmeel, so NO ROS and NO source
#   pinocchio build are needed.)
set -euo pipefail

BENCH="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"   # examples/benchmarks
REPO="$(cd "$BENCH/../.." && pwd)"                            # the GATO checkout
SQPCPU="$BENCH/baselines/sqpcpu"
DEPS="$SQPCPU/deps"
PREFIX="$DEPS/install"
VENV="${1:-$REPO/.venv-cpu-baseline}"
PY="$VENV/bin/python"
JOBS="${JOBS:-1}"
[[ "$JOBS" =~ ^[12]$ ]] || { echo "ERROR: shared-box builds require JOBS=1 or 2" >&2; exit 1; }

[ -x "$PY" ] || { echo "ERROR: create the optional baseline venv; see baselines/README.md" >&2; exit 1; }
"$PY" -c 'import pinocchio; assert pinocchio.__version__ == "3.8.0", "The pinned CPU baseline requires Pinocchio 3.8.0 in a separate venv; see baselines/README.md"'
CMEEL="$("$PY" -c "import pinocchio; from pathlib import Path; print(next(p for p in Path(pinocchio.__file__).resolve().parents if p.name == 'cmeel.prefix'))")"

# The sqpcpu baseline submodule (A2R-Lab/sqpcpu = the public fork of
# EmreAdabag/sqpcpu; the fig3-fair pin is on its fig3-fair-sigma branch; plan D14
# resolved 2026-09-21). A recursive clone already has it; this
# covers a lean checkout that skipped submodules.
git -C "$REPO" submodule update --init --checkout examples/benchmarks/baselines/sqpcpu

echo "REPO=$REPO"; echo "VENV=$VENV"; echo "CMEEL=$CMEEL"; echo "PREFIX=$PREFIX"
mkdir -p "$DEPS"

# --- osqp v0.6.3 (pinned: osqp-eigen 0.8.x targets the 0.6.x C API; v1.0 changed it) ---
if [ ! -f "$PREFIX/lib/cmake/osqp/osqp-config.cmake" ]; then
  echo "=== building osqp v0.6.3 ==="
  rm -rf "$DEPS/osqp_src"
  git clone --recursive --branch v0.6.3 --depth 1 https://github.com/osqp/osqp "$DEPS/osqp_src"
  cmake -S "$DEPS/osqp_src" -B "$DEPS/osqp_src/build" -G "Unix Makefiles" \
        -DCMAKE_INSTALL_PREFIX="$PREFIX" -DCMAKE_BUILD_TYPE=Release -DCMAKE_POSITION_INDEPENDENT_CODE=ON
  cmake --build "$DEPS/osqp_src/build" --target install -j"$JOBS"
else echo "=== osqp already installed ==="; fi

# --- osqp-eigen v0.8.1 (matches osqp 0.6.3) ---
if [ ! -f "$PREFIX/lib/cmake/OsqpEigen/OsqpEigenConfig.cmake" ]; then
  echo "=== building osqp-eigen v0.8.1 ==="
  rm -rf "$DEPS/osqpeigen_src"
  git clone --branch v0.8.1 --depth 1 https://github.com/robotology/osqp-eigen.git "$DEPS/osqpeigen_src"
  cmake -S "$DEPS/osqpeigen_src" -B "$DEPS/osqpeigen_src/build" \
        -DCMAKE_INSTALL_PREFIX="$PREFIX" -DCMAKE_PREFIX_PATH="$PREFIX" \
        -DCMAKE_BUILD_TYPE=Release -DCMAKE_POSITION_INDEPENDENT_CODE=ON
  cmake --build "$DEPS/osqpeigen_src/build" --target install -j"$JOBS"
else echo "=== osqp-eigen already installed ==="; fi

# --- pysqpcpu (QDLDL-based CPU solver) against cmeel pinocchio + local osqp ---
echo "=== building pysqpcpu (QDLDL-based CPU solver) ==="
# A cached configure can silently retain another venv's package directories.
# Refresh only when the prefix changes; unchanged builds remain incremental.
fresh=()
if [[ -f "$SQPCPU/build/CMakeCache.txt" ]] && \
   ! grep -Fqx "pinocchio_DIR:PATH=$CMEEL/lib/cmake/pinocchio" "$SQPCPU/build/CMakeCache.txt"; then
  fresh=(--fresh)
fi
cmake "${fresh[@]}" -S "$SQPCPU" -B "$SQPCPU/build" \
      -DCMAKE_PREFIX_PATH="$PREFIX;$CMEEL" \
      -DPython3_EXECUTABLE="$PY" \
      -Dpybind11_DIR="$("$PY" -m pybind11 --cmakedir)" \
      -DCMAKE_BUILD_TYPE=Release -DBUILD_EXAMPLES=OFF
cmake --build "$SQPCPU/build" --target pysqpcpu -j"$JOBS"

# --- write the env helper to source before importing pysqpcpu ---
cat > "$BENCH/baselines/sqpcpu_env.sh" <<EOF
# Source this before importing pysqpcpu (QDLDL-based CPU solver). Auto-generated by build_cpu_baseline.sh.
export LD_LIBRARY_PATH="$SQPCPU/build:$PREFIX/lib:$CMEEL/lib:\${LD_LIBRARY_PATH:-}"
export PYTHONPATH="$REPO/python:$SQPCPU/build:\${PYTHONPATH:-}"
export GATO_CPU_PYTHON="$PY"
EOF

echo "=== verifying import ==="
# shellcheck disable=SC1090
source "$BENCH/baselines/sqpcpu_env.sh"
"$PY" -c "import pysqpcpu; print('pysqpcpu OK:', [x for x in dir(pysqpcpu) if 'Thneed' in x])"
echo "DONE. Run baselines with:  source baselines/sqpcpu_env.sh"
